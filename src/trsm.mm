// One row per measured GPU (src/tuned/trsm.inc, generated by
// tuning/generate_tables.py from every run in docs/results/), the policy's
// fields in order; the estimated rows for the rest, as the other
// decompositions' (estimate.h).
struct TunedEntry {
    const char* device_name;   // exact MTLDevice.name
    unsigned    gpu_cores;
    unsigned    gpu_min_n;
    unsigned    gpu_min_rhs;
    unsigned    gpu_max_batch;
    unsigned    calibration;   // kCalibration* (calibration.h); rows without it are current
};

constexpr TunedEntry kTuned[] = {
#include "tuned/trsm.inc"
    {"", 0, 0, 0, 0, 0},
};

struct EstimatedEntry {
    unsigned   small_x100;
    unsigned   large_x100;
    unsigned   anchor_cpu_cores;
    TunedEntry row;
};
constexpr EstimatedEntry kEstimated[] = {
#include "tuned/trsm_estimated.inc"
    {0, 0, 0, {"", 0, 0, 0, 0, 0}},
};

void apply(const TunedEntry& e, TrsmPolicy& p) {
    p.gpu_min_n     = e.gpu_min_n;
    p.gpu_min_rhs   = e.gpu_min_rhs;
    p.gpu_max_batch = e.gpu_max_batch;
}

struct ResolvedPolicy {
    TrsmPolicy policy;
    std::string    source;
};

// A non-negative integer from the environment; zero is a valid value.
bool env_value(const char* name, unsigned& out) {
    const char* s = std::getenv(name);
    if (!s || !*s) return false;
    char* end = nullptr;
    const long long v = std::strtoll(s, &end, 10);
    if (end == s || v < 0) return false;
    out = v > 0xFFFFFFFFll ? 0xFFFFFFFFu : (unsigned)v;
    return true;
}

ResolvedPolicy resolve() {
    ResolvedPolicy r;
    @autoreleasepool {
        const std::string name = device_name();
        r.policy.gpu_cores = gpu_core_count();
        bool forced = false;   // METAL_LINALG_ESTIMATE_AS: estimate even a measured GPU
        const detail::EstimateTarget target = detail::estimate_target(&forced);
        for (const auto& e : kTuned) {
            if (forced) break;
            if (e.device_name[0] != '\0' && name == e.device_name && r.policy.gpu_cores == e.gpu_cores) {
                apply(e, r.policy);
                r.source = detail::tuned_source_prefix(e.calibration) + name;
                detail::calibration_notice("triangular solve", e.calibration);
                break;
            }
        }
        if (r.source.empty() && !target.device.empty()) {
            std::string source;
            if (const EstimatedEntry* e = detail::estimated_row(kEstimated, target, source)) {
                apply(e->row, r.policy);
                r.source = source;
                detail::calibration_notice("triangular solve", kUncalibrated);
            }
        }
        if (r.source.empty()) {
            // the TrsmPolicy defaults
            r.source = "default:untuned-device" + (name.empty() ? "" : " (" + name + ")");
            detail::calibration_notice("triangular solve", kUncalibrated);
        }
    }
    std::string env;
    auto over = [&](const char* name, unsigned& field) {
        if (env_value(name, field)) env += (env.empty() ? "" : ",") + std::string(name);
    };
    over("TRSM_GPU_MIN_N",     r.policy.gpu_min_n);
    over("TRSM_GPU_MIN_RHS",   r.policy.gpu_min_rhs);
    over("TRSM_GPU_MAX_BATCH", r.policy.gpu_max_batch);
    if (!env.empty()) r.source = "env:" + env;
    return r;
}

ResolvedPolicy& state() {
    static ResolvedPolicy s = resolve();
    return s;
}

bool uses_gpu(const TrsmPolicy& p, unsigned n, unsigned k, unsigned batch) {
    return p.gpu_min_n && n >= p.gpu_min_n && k >= p.gpu_min_rhs && (!p.gpu_max_batch || batch <= p.gpu_max_batch);
}

void require_square(const core::Matrices& a, const char* what) {
    if (a.rows != a.cols)
        throw std::invalid_argument(std::string("[solve_triangular] ") + what + "the matrices must be square, got " +
                                    std::to_string(a.rows) + "x" + std::to_string(a.cols) + ".");
}

