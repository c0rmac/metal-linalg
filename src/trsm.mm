// Triangular solve, A X = B with A triangular: the policy (tuned per device,
// estimated for the rest, as the other decompositions'), the routing, both
// backends, and core::solve_triangular.
//
// The CPU path is BLAS's strsm on the row-major matrices as they are, a batch
// spread over every core. The GPU path (blocked) takes one matrix at a time,
// 128 rows of X at a time: X_i = A_ii^-1 B'_i, then B' -= A(rest, i) X_i for
// the rows still to come, two MPS products a block, on the caller's matrices
// in place (row-major blocks of A are what MPS reads, so nothing is
// transposed); the inverses of A's 128 x 128 diagonal blocks are made on the
// CPU (strtri). One 4096 x 4096 with 4096 right-hand sides in about 10 ms on an
// M5 Pro, against 49 for strsm on every core.
#ifndef ACCELERATE_NEW_LAPACK
#define ACCELERATE_NEW_LAPACK
#endif
