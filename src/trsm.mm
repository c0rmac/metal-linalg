constexpr uint32_t kBlock = 128;

struct Cache {
    detail::MetalRuntime& rt = detail::MetalRuntime::shared(METAL_LINALG_SHADER(LU), "lu");
    id<MTLBuffer> inv = nil, work = nil, out = nil;
    size_t inv_floats = 0, work_floats = 0, out_floats = 0;
    id<MTLBuffer> grow(id<MTLBuffer> __strong& b, size_t& have, size_t want, MTLResourceOptions opt) {
        if (!b || have < want) {
            b = [rt.device newBufferWithLength:std::max<size_t>(16, want * sizeof(float)) options:opt];
            if (!b) throw std::runtime_error("[solve_triangular] could not allocate a GPU workspace");
            have = want;
        }
        return b;
    }
    static Cache& shared() {
        static Cache c;
        return c;
    }
};

MPSMatrixMultiplication* gemm(id<MTLDevice> dev, uint32_t m, uint32_t n, uint32_t k, bool ta, float alpha, float beta) {
    using Key = std::tuple<uint32_t, uint32_t, uint32_t, bool, float, float>;
    thread_local std::map<Key, MPSMatrixMultiplication*> kernels;
    const Key key{m, n, k, ta, alpha, beta};
    auto it = kernels.find(key);
    if (it == kernels.end()) {
        if (kernels.size() >= 4096) kernels.clear();
        it = kernels.emplace(key, [[MPSMatrixMultiplication alloc] initWithDevice:dev transposeLeft:ta transposeRight:NO
                                       resultRows:m resultColumns:n interiorColumns:k alpha:alpha beta:beta]).first;
    }
    return it->second;
}

MPSMatrix* view(id<MTLBuffer> b, size_t off, uint32_t rows, uint32_t cols, uint32_t ld) {
    MPSMatrixDescriptor* d = [MPSMatrixDescriptor matrixDescriptorWithRows:rows columns:cols rowBytes:(size_t)ld * 4
                                                                  dataType:MPSDataTypeFloat32];
    return [[MPSMatrix alloc] initWithBuffer:b offset:off * 4 descriptor:d];
}

