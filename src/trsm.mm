void solve_triangular_cpu(const Matrices& a, const float* b, uint32_t nrhs, bool upper, bool unit, float* x) {
    require_square(a, "cpu: ");
    const uint32_t n = a.cols, batch = a.batch;
    if (n == 0 || batch == 0 || nrhs == 0) return;
    const size_t per = (size_t)n * n, bper = (size_t)n * nrhs;
    metal_linalg::detail::lapack_batches(batch, per, [&](uint32_t b0, uint32_t b1) {
        for (uint32_t m = b0; m < b1; ++m) {
            std::copy(b + m * bper, b + (m + 1) * bper, x + m * bper);
            cblas_strsm(CblasRowMajor, CblasLeft, upper ? CblasUpper : CblasLower, CblasNoTrans,
                        unit ? CblasUnit : CblasNonUnit, (__LAPACK_int)n, (__LAPACK_int)nrhs, 1.0f, a.data + m * per,
                        (__LAPACK_int)n, x + m * bper, (__LAPACK_int)nrhs);
        }
    });
}

void solve_triangular_blocked(const Matrices& a, const float* b, uint32_t nrhs, bool upper, bool unit, float* x) {
    require_square(a, "blocked: ");
    const uint32_t n = a.cols, batch = a.batch, k = nrhs;
    if (n == 0 || batch == 0 || k == 0) return;
    metal_linalg::detail::AutoreleasePool pool;
    Cache& c = Cache::shared();
    id<MTLDevice> dev = c.rt.device;
    const size_t per = (size_t)n * n, bper = (size_t)n * k;
    const uint32_t nblocks = (n + kBlock - 1) / kBlock;
    id<MTLBuffer> A = metal_linalg::detail::input_buffer(dev, a);
    id<MTLBuffer> B = metal_linalg::detail::input_buffer(dev, Matrices{b, batch, n, k});
    const bool direct = reinterpret_cast<uintptr_t>(x) % (size_t)getpagesize() == 0;
    id<MTLBuffer> X = direct ? metal_linalg::detail::wrap_host(dev, x, bper * batch)
                             : c.grow(c.out, c.out_floats, bper * batch, MTLResourceStorageModeShared);
    c.grow(c.inv, c.inv_floats, (size_t)nblocks * kBlock * kBlock, MTLResourceStorageModeShared);
    c.grow(c.work, c.work_floats, bper, MTLResourceStorageModePrivate);
    float* inv = static_cast<float*>([c.inv contents]);
    for (uint32_t m = 0; m < batch; ++m) {
        // the diagonal blocks' inverses, column-major (their row-major views
        // are the transposes MPS's transposeLeft undoes)
        const float* am = a.data + m * per;
        metal_linalg::detail::parallel_for(nblocks, [&](size_t blk) {
            const uint32_t i0 = (uint32_t)blk * kBlock, ib = std::min(kBlock, n - i0);
            float* I = inv + blk * kBlock * kBlock;
            for (uint32_t col = 0; col < ib; ++col)
                for (uint32_t r = 0; r < ib; ++r) {
                    const bool in = upper ? r <= col : r >= col;
                    I[(size_t)col * kBlock + r] = r == col && unit ? 1.0f : in ? am[(size_t)(i0 + r) * n + i0 + col] : 0.0f;
                }
            char uplo = upper ? 'U' : 'L', diag = unit ? 'U' : 'N';
            __LAPACK_int lb = (__LAPACK_int)ib, lk = (__LAPACK_int)kBlock, e = 0;
            strtri_(&uplo, &diag, &lb, I, &lk, &e);
        });
        id<MTLCommandBuffer> cmd = [c.rt.queue commandBuffer];
        id<MTLBlitCommandEncoder> blit = [cmd blitCommandEncoder];   // B into the workspace, updated in place
        [blit copyFromBuffer:B sourceOffset:m * bper * 4 toBuffer:c.work destinationOffset:0 size:bper * 4];
        [blit endEncoding];
        for (uint32_t step = 0; step < nblocks; ++step) {
            const uint32_t blk = upper ? nblocks - 1 - step : step, i0 = blk * kBlock, ib = std::min(kBlock, n - i0);
            MPSMatrix* Ii = view(c.inv, (size_t)blk * kBlock * kBlock, ib, ib, kBlock);
            MPSMatrix* Yi = view(c.work, (size_t)i0 * k, ib, k, k);
            MPSMatrix* Xi = view(X, m * bper + (size_t)i0 * k, ib, k, k);
            [gemm(dev, ib, k, ib, true, 1.0f, 0.0f) encodeToCommandBuffer:cmd leftMatrix:Ii rightMatrix:Yi resultMatrix:Xi];
            // the rows still to come: below the block (lower), above it (upper)
            const uint32_t r0 = upper ? 0 : i0 + ib, rows = upper ? i0 : n - i0 - ib;
            if (!rows) continue;
            MPSMatrix* Ar = view(A, m * per + (size_t)r0 * n + i0, rows, ib, n);
            MPSMatrix* Yr = view(c.work, (size_t)r0 * k, rows, k, k);
            [gemm(dev, rows, k, ib, false, -1.0f, 1.0f) encodeToCommandBuffer:cmd leftMatrix:Ar rightMatrix:Xi
                                                                     resultMatrix:Yr];
        }
        [cmd commit];
        [cmd waitUntilCompleted];
        if (cmd.error)
            throw std::runtime_error(std::string("[solve_triangular] GPU error: ") +
                                     cmd.error.localizedDescription.UTF8String);
    }
    if (!direct) metal_linalg::detail::copy_out(static_cast<const float*>([X contents]), x, batch, bper);
}

