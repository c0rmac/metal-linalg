TrsmPolicy  trsm_policy()        { return state().policy; }
const char* trsm_policy_source() { return state().source.c_str(); }

void set_trsm_policy(const TrsmPolicy& p) {
    state().policy = p;
    state().source = "user";
}

TrsmBackend trsm_backend(unsigned n, unsigned k, unsigned batch) {
    if (const char* e = std::getenv("TRSM_DEVICE")) {
        const std::string s = e;
        if (s == "cpu") return TrsmBackend::cpu;
        if (s == "gpu" || s == "blocked") return TrsmBackend::blocked;
    }
    return uses_gpu(state().policy, n, k, batch) ? TrsmBackend::blocked : TrsmBackend::cpu;
}

void core::solve_triangular(const Matrices& a, const float* b, uint32_t nrhs, bool upper, bool unit, float* x) {
    require_square(a, "");
    if (trsm_backend(a.cols, nrhs, a.batch) == TrsmBackend::blocked)
        core::detail::solve_triangular_blocked(a, b, nrhs, upper, unit, x);
    else
        core::detail::solve_triangular_cpu(a, b, nrhs, upper, unit, x);
}

